// node scripts/brand-wordmarks.cjs — downloads the four candidate fonts (only the letters of "detoke") from
// Google Fonts and writes src/components/brand/wordmarks.ts with their outlines. No font ships with the app.
const opentype=require('opentype.js');const fs=require('fs');const os=require('os');const path=require('path');const {execFileSync}=require('child_process');
const S=fs.mkdtempSync(path.join(os.tmpdir(),'detoke-fonts-'));fs.mkdirSync(`${S}/fonts`);
const SPECS={'BricolageGrotesque.ttf':'Bricolage+Grotesque:wght@800','Fraunces.ttf':'Fraunces:opsz,wght@72,800','DMSerifDisplay.ttf':'DM+Serif+Display','Outfit.ttf':'Outfit:wght@800'};
for(const [file,spec] of Object.entries(SPECS)){
  const css=execFileSync('curl',['-s',`https://fonts.googleapis.com/css2?family=${spec}&text=detok`]).toString();
  execFileSync('curl',['-s','-o',`${S}/fonts/${file}`,css.match(/url\((https:[^)]+)\)/)[1]]);
}
// Per font: extra tracking in em and hand tweaks per pair (em), tuned for a heavy lowercase sign.
const FONTS={
  bricolage:{file:'BricolageGrotesque.ttf',name:'Bricolage Grotesque',tracking:-0.035,pairs:{to:-0.02,ok:-0.01}},
  fraunces:{file:'Fraunces.ttf',name:'Fraunces',tracking:-0.02,pairs:{et:-0.01,to:-0.02}},
  dmserif:{file:'DMSerifDisplay.ttf',name:'DM Serif Display',tracking:0.0,pairs:{to:-0.015}},
  outfit:{file:'Outfit.ttf',name:'Outfit',tracking:-0.03,pairs:{to:-0.015,ke:-0.01}},
};
const out={};
for(const [key,f] of Object.entries(FONTS)){
  const font=opentype.loadSync(`${S}/fonts/${f.file}`);const size=100;const upm=font.unitsPerEm;const scale=size/upm;
  let x=0;const letters=[];const text='detoke';
  for(let i=0;i<text.length;i++){
    const g=font.charToGlyph(text[i]);
    const p=g.getPath(x,0,size);
    letters.push({char:text[i],d:p.toPathData(2),box:p.getBoundingBox()});
    let adv=g.advanceWidth*scale+f.tracking*size;
    if(i<text.length-1){const n=font.charToGlyph(text[i+1]);adv+=font.getKerningValue(g,n)*scale+(f.pairs[text[i]+text[i+1]]||0)*size;}
    x+=adv;
  }
  const minX=Math.min(...letters.map(l=>l.box.x1)),maxX=Math.max(...letters.map(l=>l.box.x2)),minY=Math.min(...letters.map(l=>l.box.y1)),maxY=Math.max(...letters.map(l=>l.box.y2));
  // x-height from the "o" (its top), used to align the mark optically
  const o=letters.find(l=>l.char==='o').box;
  out[key]={name:f.name,viewBox:[+(minX).toFixed(2),+(minY).toFixed(2),+(maxX-minX).toFixed(2),+(maxY-minY).toFixed(2)],baseline:+(0-minY).toFixed(2),xHeight:+(-o.y1).toFixed(2),letters:letters.map(({char,d})=>({char,d}))};
}
fs.writeFileSync(path.join(__dirname,'../src/components/brand/wordmarks.ts'),`// Generated by scripts/brand-wordmarks.cjs from Google Fonts outlines: "detoke" as SVG paths, so the logo\n// never depends on loading a font. Units: 100 = font size; y grows downwards, baseline at 0.\nexport const WORDMARKS = ${JSON.stringify(out,null,1)} as const;\n\nexport type WordmarkName = keyof typeof WORDMARKS;\n`);
console.log(Object.entries(out).map(([k,v])=>`${k} ${v.viewBox} x=${v.xHeight}`).join('\n'));
