// node scripts/brand-wordmarks.cjs — downloads the four candidate fonts (rounded, light) (only the characters of "detoke!") from
// Google Fonts and writes src/components/brand/wordmarks.ts with their outlines. No font ships with the app.
const opentype=require('opentype.js');const fs=require('fs');const os=require('os');const path=require('path');const {execFileSync}=require('child_process');
const S=fs.mkdtempSync(path.join(os.tmpdir(),'detoke-fonts-'));fs.mkdirSync(`${S}/fonts`);
const SPECS={'Quicksand.ttf':'Quicksand:wght@600','Nunito.ttf':'Nunito:wght@600','Fredoka.ttf':'Fredoka:wght@500','VarelaRound.ttf':'Varela+Round'};
for(const [file,spec] of Object.entries(SPECS)){
  const css=execFileSync('curl',['-s',`https://fonts.googleapis.com/css2?family=${spec}&text=detok!`]).toString();
  execFileSync('curl',['-s','-o',`${S}/fonts/${file}`,css.match(/url\((https:[^)]+)\)/)[1]]);
}
// Per font: extra tracking in em and hand tweaks per pair (em), tuned for a heavy lowercase sign.
const FONTS={
  quicksand:{file:'Quicksand.ttf',name:'Quicksand',tracking:-0.01,pairs:{to:-0.01}},
  nunito:{file:'Nunito.ttf',name:'Nunito',tracking:-0.015,pairs:{to:-0.01}},
  fredoka:{file:'Fredoka.ttf',name:'Fredoka',tracking:-0.01,pairs:{}},
  varela:{file:'VarelaRound.ttf',name:'Varela Round',tracking:-0.015,pairs:{to:-0.01}},
};
const out={};
/** Sets a text with the font's kerning, extra tracking and hand-tuned pairs; returns tight outlines. */
function setText(font,text,tracking,pairs){
  const size=100;const scale=size/font.unitsPerEm;let x=0;const letters=[];
  for(let i=0;i<text.length;i++){
    const g=font.charToGlyph(text[i]);
    const p=g.getPath(x,0,size);
    letters.push({char:text[i],d:p.toPathData(2),box:p.getBoundingBox()});
    let adv=g.advanceWidth*scale+tracking*size;
    if(i<text.length-1){const n=font.charToGlyph(text[i+1]);adv+=font.getKerningValue(g,n)*scale+(pairs[text[i]+text[i+1]]||0)*size;}
    x+=adv;
  }
  const minX=Math.min(...letters.map(l=>l.box.x1)),maxX=Math.max(...letters.map(l=>l.box.x2)),minY=Math.min(...letters.map(l=>l.box.y1)),maxY=Math.max(...letters.map(l=>l.box.y2));
  return {viewBox:[+(minX).toFixed(2),+(minY).toFixed(2),+(maxX-minX).toFixed(2),+(maxY-minY).toFixed(2)],letters:letters.map(({char,d})=>({char,d}))};
}

for(const [key,f] of Object.entries(FONTS)){
  const font=opentype.loadSync(`${S}/fonts/${f.file}`);
  // The brand reads "detoke!": the neighborhood's "¡de toque!". The monogram "d!" is for small places.
  out[key]={name:f.name,...setText(font,'detoke!',f.tracking,{...f.pairs,'e!':0.02}),monogram:setText(font,'d!',0.03,{})};
}
fs.writeFileSync(path.join(__dirname,'../src/components/brand/wordmarks.ts'),`// Generated by scripts/brand-wordmarks.cjs from Google Fonts outlines: "detoke!" (and the monogram "d!") as SVG paths, so the logo\n// never depends on loading a font. Units: 100 = font size; y grows downwards, baseline at 0.\nexport const WORDMARKS = ${JSON.stringify(out,null,1)} as const;\n\nexport type WordmarkName = keyof typeof WORDMARKS;\n`);
console.log(Object.entries(out).map(([k,v])=>`${k} ${v.viewBox} monogram ${v.monogram.viewBox}`).join('\n'));
